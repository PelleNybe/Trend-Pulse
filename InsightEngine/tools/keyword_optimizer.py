"""
Keyword optimization middleware
Use OpenAI to optimize the search terms generated by the Agent into keywords more suitable for public opinion database queries
"""

from openai import OpenAI
import json
import sys
import os
from typing import List, Dict, Any
from dataclasses import dataclass


sys.path.append(os.path.dirname(os.path.dirname(os.path.dirname(__file__))))
from config import settings
from loguru import logger


current_dir = os.path.dirname(os.path.abspath(__file__))
root_dir = os.path.dirname(os.path.dirname(current_dir))
utils_dir = os.path.join(root_dir, 'utils')
if utils_dir not in sys.path:
    sys.path.append(utils_dir)

from retry_helper import with_graceful_retry, SEARCH_API_RETRY_CONFIG

@dataclass
class KeywordOptimizationResponse:
    """Keyword Optimization Response"""
    original_query: str
    optimized_keywords: List[str]
    reasoning: str
    success: bool
    error_message: str = ""

class KeywordOptimizer:
    """
    keyword optimizer
    Use the silicon-based flow GPT-4 model to optimize the search terms generated by the Agent into keywords that are closer to real public opinion.
    """
    
    def __init__(self, api_key: str = None, base_url: str = None, model_name: str = None):
        """
        Initialize keyword optimizer
        
        Args:
            api_key: Silicon Mobile API key，If not provided, read from configuration file
            base_url: interface base address，By default, the SiliconFlow address provided by the configuration file is used
        """
        self.api_key = api_key or settings.KEYWORD_OPTIMIZER_API_KEY

        if not self.api_key:
            logger.warning("No KEYWORD_OPTIMIZER_API_KEY provided. Keyword optimization will be disabled.")
            self.api_key = None

        self.base_url = base_url or settings.KEYWORD_OPTIMIZER_BASE_URL

        if self.api_key:
            self.client = OpenAI(
                api_key=self.api_key,
                base_url=self.base_url
            )
        else:
            self.client = None
        self.model = model_name or settings.KEYWORD_OPTIMIZER_MODEL_NAME
    
    def optimize_keywords(self, original_query: str, context: str = "") -> KeywordOptimizationResponse:
        """
        Optimize search keywords
        
        Args:
            original_query: original search query generated by Agent
            context: additional context information（such as paragraph title、Content description, etc.）
            
        Returns:
            KeywordOptimizationResponse: Optimized keyword list
        """
        logger.info(f"🔍 Keyword optimization middleware: processing queries '{original_query}'")
        
        if not self.client:
            logger.warning("Keyword optimizer skipped due to missing API key")
            return KeywordOptimizationResponse(
                original_query=original_query,
                optimized_keywords=[original_query],
                reasoning="API key missing, backup to original query",
                success=False,
                error_message="Missing API key"
            )

        try:

            system_prompt = self._build_system_prompt()
            user_prompt = self._build_user_prompt(original_query, context)
            

            response = self._call_openai_api(system_prompt, user_prompt)
            
            if response["success"]:

                content = response["content"]
                try:

                    if content.strip().startswith('{'):
                        parsed = json.loads(content)
                        keywords = parsed.get("keywords", [])
                        reasoning = parsed.get("reasoning", "")
                    else:

                        keywords = self._extract_keywords_from_text(content)
                        reasoning = content
                    

                    validated_keywords = self._validate_keywords(keywords)
                    
                    logger.info(
                        f"✅ Optimization successful: {len(validated_keywords)}keywords" +
                        ("" if not validated_keywords else "\n" +
                         "\n".join([f"   {i}. '{k}'" for i, k in enumerate(validated_keywords, 1)]))
                    )
                        
                    
                    
                    return KeywordOptimizationResponse(
                        original_query=original_query,
                        optimized_keywords=validated_keywords,
                        reasoning=reasoning,
                        success=True
                    )
                
                except Exception as e:
                    logger.exception(f"⚠️ Failed to parse response，Use backup plan: {str(e)}")

                    backup_keywords = self._backup_keyword_extraction(original_query)
                    return KeywordOptimizationResponse(
                        original_query=original_query,
                        optimized_keywords=backup_keywords,
                        reasoning="APIResponse parsing failed，Use alternative keyword extraction",
                        success=True
                    )
            else:
                logger.error(f"❌ APIcall failed: {response['error']}")

                backup_keywords = self._backup_keyword_extraction(original_query)
                return KeywordOptimizationResponse(
                    original_query=original_query,
                    optimized_keywords=backup_keywords,
                    reasoning="APIcall failed，Use alternative keyword extraction",
                    success=True,
                    error_message=response['error']
                )
                
        except Exception as e:
            logger.error(f"❌ Keyword optimization failed: {str(e)}")

            backup_keywords = self._backup_keyword_extraction(original_query)
            return KeywordOptimizationResponse(
                original_query=original_query,
                optimized_keywords=backup_keywords,
                reasoning="System error，Use alternative keyword extraction",
                success=False,
                error_message=str(e)
            )
    
    def _build_system_prompt(self) -> str:
        """Build systemprompt"""
        return """You are a professional public opinion data mining expert。Your job is to refine user-supplied search queries into keywords more suitable for finding in social media opinion databases。

**core principles**：
1. **Close to the language of netizens**：Use vocabulary that ordinary netizens would use on social media
2. **Avoid jargon**：Not used"public opinion"、"spread"、"tendency"、"Outlook"and other official vocabulary
3. **Concise and specific**：Each keyword should be very concise and clear，Facilitates database matching
4. **Emotional**：Contains vocabulary commonly used by netizens to express emotions
5. **Quantity control**：Provide at least 10 keywords，Provide up to 20 keywords
6. **avoid duplication**：Don’t stray from the topic of the initial query

**Important reminder**：Each keyword must be an indivisible independent term，It is strictly prohibited to include spaces within entries。For example，should be used "Lei Jun class controversy" rather than wrong "Lei Junban controversy"。


**Output format**：
Please return results in JSON format：
{
    "keywords": ["keywords1", "keywords2", "keywords3"],
    "reasoning": "Reasons for choosing these keywords"
}

**Example**：
enter："Wuhan University Public Opinion Management Future Outlook Development Trend"
output：
{
    "keywords": ["Wuhan University", "Wuhan University", "school management", "Wuhan University Education"],
    "reasoning": "choose'Wuhan University'and'Wuhan University'as core vocabulary，This is the most commonly used title among netizens；'school management'Compare'Public opinion management'Closer to daily expression；avoid using'future outlook'、'Development trend'and other professional terms rarely used by netizens"
}"""

    def _build_user_prompt(self, original_query: str, context: str) -> str:
        """Build userprompt"""
        prompt_parts = [f"Please optimize the following search queries into keywords suitable for public opinion database queries：\n\noriginal query：{original_query}"]
        
        if context:
            prompt_parts.append(f"\n\ncontextual information：{context}")
        
        prompt_parts.append("\n\nplease remember：Use words that netizens actually use on social media，Avoid official terminology and technical vocabulary。")
        prompt = "".join(prompt_parts)
        
        return prompt
    
    @with_graceful_retry(SEARCH_API_RETRY_CONFIG, default_return={"success": False, "error": "Keyword optimization service is temporarily unavailable"})
    def _call_openai_api(self, system_prompt: str, user_prompt: str) -> Dict[str, Any]:
        """callOpenAI API"""
        try:
            response = self.client.chat.completions.create(
                model=self.model,
                messages=[
                    {"role": "system", "content": system_prompt},
                    {"role": "user", "content": user_prompt}
                ],
                temperature=0.7,
            )

            if response.choices:
                content = response.choices[0].message.content
                return {"success": True, "content": content}
            else:
                return {"success": False, "error": "APIReturn format exception"}
        except Exception as e:
            return {"success": False, "error": f"APICall exception: {str(e)}"}
    
    def _extract_keywords_from_text(self, text: str) -> List[str]:
        """Extract keywords from text（Used when JSON parsing fails）"""

        lines = text.split('\n')
        keywords = []
        
        for line in lines:
            line = line.strip()

            if '：' in line or ':' in line:
                parts = line.split('：') if '：' in line else line.split(':')
                if len(parts) > 1:
                    potential_keywords = parts[1].strip()

                    if '、' in potential_keywords:
                        keywords.extend([k.strip() for k in potential_keywords.split('、')])
                    elif ',' in potential_keywords:
                        keywords.extend([k.strip() for k in potential_keywords.split(',')])
                    else:
                        keywords.append(potential_keywords)
        

        if not keywords:

            import re
            quoted_content = re.findall(r'["""\'](.*?)["""\']', text)
            keywords.extend(quoted_content)
        

        cleaned_keywords = []
        for keyword in keywords[:20]:
            keyword = keyword.strip().strip('"\'""''')
            if keyword and len(keyword) <= 20:
                cleaned_keywords.append(keyword)
        
        return cleaned_keywords[:20]
    
    def _validate_keywords(self, keywords: List[str]) -> List[str]:
        """Validate and clean keywords"""
        validated = []
        

        bad_keywords = {
            'attitude analysis', 'public reaction', 'emotional tendencies',
            'future outlook', 'Development trend', 'strategic planning', 'policy orientation', 'management mechanism'
        }
        
        for keyword in keywords:
            if isinstance(keyword, str):
                keyword = keyword.strip().strip('"\'""''')
                

                if (keyword and 
                    len(keyword) <= 20 and 
                    len(keyword) >= 1 and
                    not any(bad_word in keyword for bad_word in bad_keywords)):
                    validated.append(keyword)
        
        return validated[:20]
    
    def _backup_keyword_extraction(self, original_query: str) -> List[str]:
        """Alternative keyword extraction solution"""


        stop_words = {'、'}
        

        import re

        tokens = re.split(r'[\s，。！？；：、]+', original_query)
        
        keywords = []
        for token in tokens:
            token = token.strip()
            if token and token not in stop_words and len(token) >= 2:
                keywords.append(token)
        

        if not keywords:
            first_word = original_query.split()[0] if original_query.split() else original_query
            keywords = [first_word] if first_word else ["Popular"]
        
        return keywords[:20]


keyword_optimizer = KeywordOptimizer()
